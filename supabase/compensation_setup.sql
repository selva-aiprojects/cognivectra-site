-- 6. Create a view for easy salary calculation
CREATE OR REPLACE VIEW public.compensation_breakdown AS
SELECT 
  id,
  role_title,
  role_level,
  department,
  currency,
  annual_ctc_min,
  annual_ctc_max,
  -- Calculate mid-point CTC
  (annual_ctc_min + annual_ctc_max) / 2 AS annual_ctc_mid,
  -- Calculate components based on mid-point
  ROUND((annual_ctc_min + annual_ctc_max) / 2 * basic_salary_percentage / 100, 2) AS basic_salary,
  ROUND((annual_ctc_min + annual_ctc_max) / 2 * hra_percentage / 100, 2) AS hra,
  ROUND((annual_ctc_min + annual_ctc_max) / 2 * special_allowance_percentage / 100, 2) AS special_allowance,
  ROUND((annual_ctc_min + annual_ctc_max) / 2 * performance_bonus_percentage / 100, 2) AS performance_bonus,
  benefits,
  annual_leave_days,
  sick_leave_days,
  casual_leave_days,
  working_hours_per_week,
  work_schedule,
  work_location,
  probation_period_months,
  notice_period_days,
  is_active
FROM public.compensation_packages;
