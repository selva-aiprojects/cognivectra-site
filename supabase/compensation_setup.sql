-- Compensation Management System for CogniVectra
-- This schema manages salary packages and benefits for different roles

-- 1. Create compensation_packages table
CREATE TABLE public.compensation_packages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
  
  -- Role Information
  role_title text NOT NULL,
  role_level text NOT NULL CHECK (role_level IN ('entry', 'mid', 'senior', 'lead', 'executive')),
  department text NOT NULL,
  
  -- Compensation Details (in INR, can be converted)
  currency text DEFAULT 'INR' CHECK (currency IN ('INR', 'USD', 'EUR')),
  annual_ctc_min numeric(12, 2) NOT NULL,
  annual_ctc_max numeric(12, 2) NOT NULL,
  
  -- Salary Breakdown
  basic_salary_percentage numeric(5, 2) DEFAULT 50.00, -- % of CTC
  hra_percentage numeric(5, 2) DEFAULT 20.00,
  special_allowance_percentage numeric(5, 2) DEFAULT 20.00,
  performance_bonus_percentage numeric(5, 2) DEFAULT 10.00,
  
  -- Benefits (stored as JSON array)
  benefits jsonb DEFAULT '[]'::jsonb,
  
  -- Leave Policy
  annual_leave_days integer DEFAULT 21,
  sick_leave_days integer DEFAULT 12,
  casual_leave_days integer DEFAULT 7,
  
  -- Working Conditions
  working_hours_per_week integer DEFAULT 40,
  work_schedule text DEFAULT 'Monday to Friday, 9 AM to 6 PM',
  work_location text DEFAULT 'Remote',
  
  -- Employment Terms
  probation_period_months integer DEFAULT 3,
  notice_period_days integer DEFAULT 60,
  
  -- Status
  is_active boolean DEFAULT true,
  
  -- Notes
  notes text
);

-- 2. Enable Row Level Security
ALTER TABLE public.compensation_packages ENABLE ROW LEVEL SECURITY;

-- 3. Create Policies

-- Only authenticated admins can view compensation packages
CREATE POLICY "Admins can view compensation packages"
  ON public.compensation_packages FOR SELECT
  USING (auth.role() = 'authenticated');

-- Only authenticated admins can manage compensation packages
CREATE POLICY "Admins can manage compensation packages"
  ON public.compensation_packages FOR ALL
  USING (auth.role() = 'authenticated')
  WITH CHECK (auth.role() = 'authenticated');

-- 4. Create indexes for faster queries
CREATE INDEX idx_compensation_role_title ON public.compensation_packages(role_title);
CREATE INDEX idx_compensation_role_level ON public.compensation_packages(role_level);
CREATE INDEX idx_compensation_department ON public.compensation_packages(department);
CREATE INDEX idx_compensation_active ON public.compensation_packages(is_active);

