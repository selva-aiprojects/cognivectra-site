-- 6. Create function to auto-generate employee ID
CREATE OR REPLACE FUNCTION generate_employee_id()
RETURNS TRIGGER AS $$
DECLARE
  next_id INTEGER;
  new_employee_id TEXT;
BEGIN
  -- Get the next employee number
  SELECT COALESCE(MAX(CAST(SUBSTRING(employee_id FROM 6) AS INTEGER)), 0) + 1
  INTO next_id
  FROM public.employees
  WHERE employee_id LIKE 'COGNI%';
  
  -- Generate new employee ID (e.g., COGNI001, COGNI002, etc.)
  new_employee_id := 'COGNI' || LPAD(next_id::TEXT, 3, '0');
  
  NEW.employee_id := new_employee_id;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 7. Create trigger to auto-generate employee ID
CREATE TRIGGER set_employee_id
  BEFORE INSERT ON public.employees
  FOR EACH ROW
  WHEN (NEW.employee_id IS NULL)
  EXECUTE FUNCTION generate_employee_id();

-- 8. Create function to auto-generate offer reference
CREATE OR REPLACE FUNCTION generate_offer_reference()
RETURNS TRIGGER AS $$
DECLARE
  next_id INTEGER;
  year TEXT;
  new_reference TEXT;
BEGIN
  -- Get current year
  year := TO_CHAR(CURRENT_DATE, 'YYYY');
  
  -- Get the next offer number for this year
  SELECT COALESCE(MAX(CAST(SUBSTRING(offer_reference FROM LENGTH(offer_reference) - 2) AS INTEGER)), 0) + 1
  INTO next_id
  FROM public.offer_letters
  WHERE offer_reference LIKE 'COGNI/' || year || '/%';
  
  -- Generate new reference (e.g., COGNI/2026/001)
  new_reference := 'COGNI/' || year || '/' || LPAD(next_id::TEXT, 3, '0');
  
  NEW.offer_reference := new_reference;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 9. Create trigger to auto-generate offer reference
CREATE TRIGGER set_offer_reference
  BEFORE INSERT ON public.offer_letters
  FOR EACH ROW
  WHEN (NEW.offer_reference IS NULL)
  EXECUTE FUNCTION generate_offer_reference();

-- 10. Create view for employee summary
CREATE OR REPLACE VIEW public.employee_summary AS
SELECT 
  e.id,
  e.employee_id,
  e.full_name,
  e.email,
  e.job_title,
  e.department,
  e.role_level,
  e.employment_status,
  e.joining_date,
  e.annual_ctc,
  e.currency,
  e.work_location,
  cp.role_title as compensation_role,
  CASE 
    WHEN e.employment_status = 'active' OR e.employment_status = 'confirmed' THEN 
      EXTRACT(YEAR FROM AGE(CURRENT_DATE, e.joining_date)) || ' years, ' ||
      EXTRACT(MONTH FROM AGE(CURRENT_DATE, e.joining_date)) || ' months'
    ELSE NULL
  END as tenure
FROM public.employees e
LEFT JOIN public.compensation_packages cp ON e.compensation_package_id = cp.id
ORDER BY e.joining_date DESC;

-- 11. Create view for offer letter summary
CREATE OR REPLACE VIEW public.offer_summary AS
SELECT 
  ol.id,
  ol.offer_reference,
  ol.candidate_name,
  ol.candidate_email,
  ol.job_title,
  ol.department,
  ol.annual_ctc,
  ol.start_date,
  ol.offer_status,
  ol.sent_at,
  ol.acceptance_deadline,
  ol.accepted_at,
  ol.created_at,
  ja.full_name as application_name,
  ja.position as applied_position
FROM public.offer_letters ol
LEFT JOIN public.job_applications ja ON ol.job_application_id = ja.id
ORDER BY ol.created_at DESC;
